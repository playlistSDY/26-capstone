import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { createInterface } from 'node:readline';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../../kiosk-web/package.json', import.meta.url));
const { chromium, expect } = require('@playwright/test');
const here = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(here, '../../tmp/voice-dashboard-qa');
await fs.mkdir(output, { recursive: true });
const worker = spawn(path.join(here, '.venv/bin/python'), ['-u', 'test_voice_dashboard.py', '--fixture'], { cwd: here, stdio: ['pipe', 'pipe', 'inherit'] });
const lines = createInterface({ input: worker.stdout });
const [first] = await once(lines, 'line');
const { base } = JSON.parse(first);
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--mute-audio'] });
const page = await browser.newPage({ viewport: { width: 1360, height: 960 } });
const errors = [], external = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', request => { if (new URL(request.url()).hostname !== '127.0.0.1') external.push(request.url()); });
const send = (event, fields = {}) => worker.stdin.write(JSON.stringify({ time: Date.now() / 1000, event, ...fields }) + '\n');
try {
  await page.goto(base);
  await page.evaluate(() => document.fonts.ready);
  await expect(page.getByRole('heading', { name: /내가 건넨 말/ })).toBeVisible();
  await expect(page.getByAltText('나를 나타내는 서 있는 아바타')).toBeVisible();
  await expect(page.locator('#record-label')).toHaveText('수음 시작');
  await page.locator('#record-button').click();
  await expect(page.locator('#record-label')).toHaveText('수음 중지');
  send('speech_started', { turn_id: 'qa-one' });
  send('recognizing', { turn_id: 'qa-one' });
  send('transcript', { text: '아이스 아메리카노 한 잔 주세요.', elapsed: .74, turn_id: 'qa-one' });
  send('filter_started', { text: '아이스 아메리카노 한 잔 주세요.', turn_id: 'qa-one' });
  await expect(page.locator('#candidate')).toContainText('아이스 아메리카노');
  await expect(page.locator('.message-bubble')).toHaveCount(0);
  send('turn.hold', { text: '아이스 아메리카노 한 잔 주세요.', reason: 'continuation_window', filter_seconds: .001 });
  await expect(page.locator('#candidate-result')).toContainText('추가 발화');
  await expect(page.locator('.message-bubble')).toHaveCount(0);
  send('turn.accept', { text: '아이스 아메리카노 한 잔 주세요.', reason: 'ready', usage: { route: 'local_explicit_order' }, stt_seconds: .74, filter_seconds: .001, after_stt_seconds: .18, from_speech_end_seconds: 1.43 });
  await expect(page.locator('.message-bubble')).toHaveCount(1);
  await expect(page.locator('.message-text')).toHaveText('아이스 아메리카노 한 잔 주세요.');
  await expect(page.locator('#after-stt')).toHaveText('180ms');
  send('turn.ignore', { text: '너 뭐 먹을래? 나는 라떼.', reason: 'unrelated_speech', after_stt_seconds: .9 });
  await expect(page.locator('#candidate-badge')).toHaveText('무시');
  await expect(page.locator('.message-bubble')).toHaveCount(1);
  send('turn.accept', { text: '해줘. 2개.', reason: 'context_for_agent', usage: { route: 'local_conversation' }, stt_seconds: .6, filter_seconds: 0, after_stt_seconds: .03, from_speech_end_seconds: 1.1 });
  await expect(page.locator('.message-text').last()).toHaveText('해줘. 2개.');
  await expect(page.locator('.message-bubble')).toHaveCount(2);
  for (let i = 0; i < 50; i++) send('meter', { rms: i * 20, probability: .8, threshold: 200, active: false });
  await expect(page.locator('#rms')).toHaveText('980');
  await expect(page.locator('.log-row')).toHaveCount(9);
  await page.screenshot({ path: path.join(output, 'desktop.png') });
  await page.reload();
  await expect(page.locator('.message-bubble')).toHaveCount(2);
  await page.setViewportSize({ width: 1024, height: 800 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(output, 'compact.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const layout = await page.evaluate(() => ({ headers: document.querySelectorAll('.topbar').length, sidebarTop: document.querySelector('.inspector').getBoundingClientRect().top + scrollY, bodyHeight: document.body.scrollHeight, viewport: innerHeight }));
  await fs.writeFile(path.join(output, 'mobile-layout.json'), JSON.stringify(layout));
  await page.screenshot({ path: path.join(output, 'mobile.png') });
  await page.locator('.inspector-title').scrollIntoViewIfNeeded();
  await page.evaluate(() => window.scrollTo(0, document.querySelector('.inspector').getBoundingClientRect().top + scrollY));
  await expect(page.locator('.inspector-title')).toBeVisible();
  await page.screenshot({ path: path.join(output, 'mobile-inspector.png') });
  await page.setViewportSize({ width: 1360, height: 960 });
  const attack = '<img src=x onerror="window.injected=true">';
  send('turn.accept', { text: attack, reason: 'ready' });
  await expect(page.locator('.message-text').last()).toHaveText(attack);
  expect(await page.evaluate(() => window.injected)).toBeUndefined();
  await page.locator('#record-button').click();
  await expect(page.locator('#record-label')).toHaveText('수음 시작');
  expect(errors).toEqual([]); expect(external).toEqual([]);
  const report = { realLocalHTTPAndSSE: true, syntheticEvents: true, microphoneOrAPIsUsed: false, onlyAcceptedBubbles: true, pendingAndIgnoredStayInSidebar: true, stopStartControls: true, historySurvivesReload: true, textEscaping: true, externalRequests: external, pageErrors: errors, responsiveWidths: [1360, 1024, 390] };
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report));
} finally {
  await browser.close(); worker.stdin.end('stop\n'); await once(worker, 'exit'); lines.close();
}
